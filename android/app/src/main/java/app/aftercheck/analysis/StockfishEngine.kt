package app.aftercheck.analysis

import android.content.Context
import android.os.Build
import app.aftercheck.BuildConfig
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.currentCoroutineContext
import kotlinx.coroutines.ensureActive
import kotlinx.coroutines.withContext
import java.io.BufferedReader
import java.io.BufferedWriter
import java.io.File
import java.io.InputStreamReader
import java.io.OutputStreamWriter
import java.nio.charset.StandardCharsets
import java.util.concurrent.TimeUnit

data class EnginePositionResult(
    val depth: Int,
    val bestMoveUci: String,
    val scoreCp: Int?,
    val mateIn: Int?,
    val principalVariationUci: String
) {
    fun scoreFromWhitePerspective(fen: String): Int {
        val raw = scoreCp ?: when {
            mateIn == null -> 0
            mateIn > 0 -> 10_000
            mateIn < 0 -> -10_000
            else -> 0
        }
        val blackToMove = fen.trim().split(' ').getOrNull(1) == "b"
        return if (blackToMove) -raw else raw
    }
}

/**
 * Runs the Stockfish UCI executable generated by the repository's build workflow.
 * Stockfish is executed locally; no remote analysis service is used.
 */
object StockfishEngine {
    suspend fun analyzeFens(
        context: Context,
        fens: List<String>,
        depth: Int = 10,
        onProgress: suspend (Int, Int) -> Unit = { _, _ -> }
    ): List<EnginePositionResult> = withContext(Dispatchers.IO) {
        require(fens.isNotEmpty()) { "At least one position is required." }
        require(depth in 1..30) { "Depth must be between 1 and 30." }
        val executable = extractEngine(context)
        val process = ProcessBuilder(executable.absolutePath).redirectErrorStream(true).start()
        val reader = BufferedReader(InputStreamReader(process.inputStream, StandardCharsets.UTF_8))
        val writer = BufferedWriter(OutputStreamWriter(process.outputStream, StandardCharsets.UTF_8))

        fun send(command: String) {
            writer.write(command)
            writer.newLine()
            writer.flush()
        }

        fun waitForLine(terminal: String) {
            while (true) {
                val line = reader.readLine() ?: throw IllegalStateException("Stockfish exited before '$terminal'.")
                if (line.trim() == terminal) return
            }
        }

        try {
            send("uci")
            waitForLine("uciok")
            send("setoption name Threads value 1")
            send("setoption name Hash value 64")
            send("isready")
            waitForLine("readyok")

            val analyses = mutableListOf<EnginePositionResult>()
            fens.forEachIndexed { index, fen ->
                currentCoroutineContext().ensureActive()
                require(fen.split(' ').size >= 4) { "Invalid FEN at position ${index + 1}." }
                send("position fen $fen")
                send("go depth $depth")

                var bestInfo: String? = null
                var bestMove: String? = null
                while (true) {
                    currentCoroutineContext().ensureActive()
                    val line = reader.readLine()
                        ?: throw IllegalStateException("Stockfish stopped during position ${index + 1}.")
                    if (line.startsWith("info depth ") && line.contains(" score ")) bestInfo = line
                    if (line.startsWith("bestmove ")) {
                        bestMove = line.split(' ').getOrNull(1)
                        break
                    }
                }
                analyses += parseInfo(bestInfo.orEmpty(), bestMove.orEmpty())
                onProgress(index + 1, fens.size)
            }
            send("quit")
            process.waitFor(2, TimeUnit.SECONDS)
            analyses
        } finally {
            runCatching { writer.close() }
            runCatching { reader.close() }
            if (process.isAlive) process.destroyForcibly()
        }
    }

    private fun extractEngine(context: Context): File {
        val abi = Build.SUPPORTED_ABIS.firstOrNull { it == "arm64-v8a" || it == "x86_64" }
            ?: throw UnsupportedOperationException("No packaged Stockfish binary for this device architecture.")
        val asset = "engine/stockfish-$abi"
        val directory = File(context.filesDir, "engine").apply { mkdirs() }
        val executable = File(directory, "stockfish-$abi")
        val prefs = context.getSharedPreferences("aftercheck_engine", Context.MODE_PRIVATE)
        val installedVersion = prefs.getString("engine_version", null)
        if (!executable.exists() || executable.length() == 0L || installedVersion != BuildConfig.VERSION_NAME) {
            executable.delete()
            try {
                context.assets.open(asset).use { input ->
                    executable.outputStream().use { output -> input.copyTo(output) }
                }
            } catch (error: Exception) {
                throw IllegalStateException(
                    "Stockfish is not bundled in this build. Use the GitHub Actions APK artifact or build it with scripts/build-stockfish-android.sh.",
                    error
                )
            }
            check(executable.setExecutable(true, true)) { "Could not mark Stockfish executable." }
            prefs.edit().putString("engine_version", BuildConfig.VERSION_NAME).apply()
        }
        check(executable.canExecute()) { "Stockfish is not executable on this device." }
        return executable
    }

    internal fun parseInfo(info: String, bestMoveLine: String): EnginePositionResult {
        val words = info.trim().split(' ').filter { it.isNotBlank() }
        fun valueAfter(key: String): String? {
            val index = words.indexOf(key)
            return words.getOrNull(index + 1)
        }
        val depth = valueAfter("depth")?.toIntOrNull() ?: 0
        val scoreIndex = words.indexOf("score")
        val scoreType = words.getOrNull(scoreIndex + 1)
        val scoreValue = words.getOrNull(scoreIndex + 2)?.toIntOrNull()
        val scoreCp = if (scoreType == "cp") scoreValue else null
        val mateIn = if (scoreType == "mate") scoreValue else null
        val pvIndex = words.indexOf("pv")
        val pv = if (pvIndex >= 0) words.drop(pvIndex + 1).joinToString(" ") else ""
        val bestMove = bestMoveLine.trim().split(' ').getOrNull(1).orEmpty()
        return EnginePositionResult(depth, bestMove, scoreCp, mateIn, pv)
    }
}
